func TestTheListOfModulesIsUniqueAndLeavesOutThisModule(t *testing.T) {
	module := func(path string) *modulePath { return &modulePath{Path: path} }

	packages := []listedPackage{
		{ImportPath: "own", Module: module(own)},
		{ImportPath: "fmt"},
		{ImportPath: "yaml", Module: module("github.com/goccy/go-yaml")},
		{ImportPath: "own/internal", Module: module(own)},
		{ImportPath: "yaml/token", Module: module("github.com/goccy/go-yaml")},
	}

	got := linkedModules(packages, own)
	if want := []string{"github.com/goccy/go-yaml"}; !slices.Equal(got, want) {
		t.Errorf("linkedModules = %q, want %q", got, want)
	}
}

