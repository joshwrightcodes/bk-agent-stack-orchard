func TestNoticeCarriesTheNoticeTextOfGRPC(t *testing.T) {
	grpc := []string{"google.golang.org/grpc"}

	problems := noticeErrors(grpc, notice+"google.golang.org/grpc\n")
	if !slices.ContainsFunc(problems, func(p string) bool {
		return strings.Contains(p, "NOTICE text of gRPC")
	}) {
		t.Errorf("problems = %q, want one about the NOTICE text of gRPC", problems)
	}

	problems = noticeErrors(grpc, notice+"google.golang.org/grpc\nCopyright 2014 gRPC authors.\n")
	if len(problems) != 0 {
		t.Errorf("problems = %q, want none", problems)
	}
}

func TestTheSPDXLineRule(t *testing.T) {
	const copyright = copyrightPrefix + "2026 The bk-agent-stack-orchard Authors"

	for _, test := range []struct {
		name, text string
		fails      bool
	}{
		{"a Go file without the lines fails", "package a\n", true},
		{"a Go file with both lines first passes", spdxLine + "\n" + copyright + "\n\npackage a\n", false},
		{"a Go file without the copyright line fails", spdxLine + "\n\npackage a\n", true},
		{"a copyright line in third place fails", spdxLine + "\n\n" + copyright + "\n\npackage a\n", true},
		{"a copyright line with no holder fails", spdxLine + "\n" + copyrightPrefix + "\n\npackage a\n", true},
		{"another holder passes", spdxLine + "\n" + copyrightPrefix + "2027 A Contributor\n\npackage a\n", false},
		{"a line in second place fails", "//go:build integration\n" + spdxLine + "\n" + copyright + "\n\npackage a\n", true},
		{"a line below the package clause fails", "package a\n\n" + spdxLine + "\n" + copyright + "\n", true},
		{"another licence identifier fails", "// SPDX-License-" + "Identifier: MIT\n" + copyright + "\n\npackage a\n", true},
		{
			"a generated file keeps its generated line",
			spdxLine + "\n" + copyright + "\n\n// Code generated by x. DO NOT EDIT.\n\npackage a\n", false,
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			problems := spdxErrors("a.go", test.text)

			if test.fails && (len(problems) == 0 || !strings.Contains(problems[0], "a.go")) {
				t.Errorf("problems = %q, want one that names a.go", problems)
			}

			if !test.fails && len(problems) != 0 {
				t.Errorf("problems = %q, want none", problems)
			}
		})
	}
}

