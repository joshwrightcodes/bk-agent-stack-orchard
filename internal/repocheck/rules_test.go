func TestTheGoModRules(t *testing.T) {
	const header = "module github.com/example/own\n\n"

	for _, test := range []struct {
		name, goMod, want string
	}{
		{"a go.mod that follows the rules passes", header + "go 1.27\n\nrequire github.com/buildkite/stacksapi v1.2.0\n", ""},
		{"a patch release of the stated Go version passes", header + "go 1.27.3\n", ""},
		{"an Orchard module fails", header + "go 1.27\n\nrequire github.com/cirruslabs/orchard v0.1.0\n", "github.com/cirruslabs/orchard"},
		{"a package of an Orchard module fails", header + "go 1.27\n\nrequire github.com/openai/orchard/pkg/client v0.1.0\n", "github.com/openai/orchard"},
		{"a replace directive fails", header + "go 1.27\n\nreplace github.com/goccy/go-yaml => ../yaml\n", "replace directive"},
		{"a replace with an Orchard module fails", header + "go 1.27\n\nreplace github.com/x/y => github.com/openai/orchard v0.1.0\n", "ADR-0010"},
		{"another Go version fails", header + "go 1.26\n", "go.mod declares Go 1.26, the documents state 1.27"},
		{"a Go version that only starts with the stated one fails", header + "go 1.270\n", "go.mod declares Go 1.270"},
		{"no Go version fails", header, "go.mod declares no Go version"},
		{"an old stacksapi fails", header + "go 1.27\n\nrequire github.com/buildkite/stacksapi v1.1.9\n", "v1.2.0 or later"},
		{"a pseudo-version of stacksapi below the minimum fails", header + "go 1.27\n\nrequire github.com/buildkite/stacksapi v0.0.0-20260101000000-abcdefabcdef\n", "v1.2.0 or later"},
		{"a later stacksapi passes", header + "go 1.27\n\nrequire github.com/buildkite/stacksapi v1.10.0\n", ""},
	} {
		t.Run(test.name, func(t *testing.T) {
			name := filepath.Join(t.TempDir(), "go.mod")
			if err := os.WriteFile(name, []byte(test.goMod), 0o600); err != nil {
				t.Fatal(err)
			}

			problems := goModErrors(parseGoMod(t, name), "1.27")

			if test.want == "" && len(problems) != 0 {
				t.Errorf("problems = %q, want none", problems)
			}

			if test.want != "" && !slices.ContainsFunc(problems, func(p string) bool {
				return strings.Contains(p, test.want)
			}) {
				t.Errorf("problems = %q, want one that contains %q", problems, test.want)
			}
		})
	}
}

func TestTheNameOfAnOrchardFileFailsOutsideTheDocuments(t *testing.T) {
	problems := orchardFileErrors([]string{
		"internal/orchard/client.go",
		"docs/upstream/openapi.yaml",
		"internal/orchard/openapi.yaml",
		"pkg/orchard.go",
		"tools/docs/orchard.go",
	})

	want := []string{"internal/orchard/openapi.yaml", "pkg/orchard.go", "tools/docs/orchard.go"}
	if len(problems) != len(want) {
		t.Fatalf("problems = %q, want one for each of %q", problems, want)
	}

	for i, name := range want {
		if !strings.HasPrefix(problems[i], name+" ") {
			t.Errorf("problem %d = %q, want one that names %s", i, problems[i], name)
		}
	}
}
