#!/usr/bin/env bash
# Generates docs/architecture/c4.md from docs/architecture/workspace.dsl.
#
# Structurizr exports Mermaid with HTML labels. Markdown renderers that run Mermaid with
# securityLevel "strict" and htmlLabels false cannot show these labels. This script converts
# each label to plain text with <br/> line breaks.
#
# The export runs on a temporary copy of the workspace, so that Structurizr does not write
# files into the repository.
set -euo pipefail

root="$(git rev-parse --show-toplevel)"
arch="$root/docs/architecture"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

cp "$arch/workspace.dsl" "$tmp/"

# The container runs as the user of this shell. It can then read a directory that mktemp created
# with mode 0700, and the files that it writes belong to this user, so the trap above can remove
# them. HOME points at the mount, because this user has no home directory in the container.
docker run --rm \
  --user "$(id -u):$(id -g)" \
  -e HOME=/usr/local/structurizr \
  -v "$tmp:/usr/local/structurizr" structurizr/structurizr \
  export -workspace /usr/local/structurizr/workspace.dsl -format mermaid \
  -output /usr/local/structurizr/mermaid >/dev/null

plain_labels() {
  perl -pe '
    $_ = "" if /^\s*linkStyle default\b/;
    s{<div style=\x27font-weight: bold\x27>(.*?)</div>}{$1<br/>}g;
    s{<div style=\x27font-size: 70%; margin-top: 0px\x27>(.*?)</div>}{$1<br/>}g;
    s{<div style=\x27font-size: 80%; margin-top:10px\x27>(.*?)</div>}{$1}g;
    s{<div>(.*?)</div><div style=\x27font-size: 70%\x27></div>}{$1}g;
    s{<div>(.*?)</div><div style=\x27font-size: 70%\x27>(.*?)</div>}{$1<br/>$2}g;
    s{<br />}{<br/>}g;
    s{(?:<br/>)+"}{"}g;
  ' "$1"
}

{
  printf '# bk-agent-stack-orchard — C4 diagrams\n\n'
  printf '<!-- Generated by docs/architecture/render-c4-md.sh from workspace.dsl. Do not edit this file. -->\n\n'
  printf 'This file contains Mermaid versions of the C4 views in `workspace.dsl`. The workspace is the source of truth. CI runs `render-c4-md.sh` and fails if the committed file is different.\n'
  for view in \
    "SystemContext|Level 1 — System context" \
    "Containers|Level 2 — Containers" \
    "ControllerComponents|Level 3 — Controller components"; do
    key="${view%%|*}"
    title="${view#*|}"
    printf '\n## %s\n\n```mermaid\n' "$title"
    plain_labels "$tmp/mermaid/structurizr-$key.mmd"
    printf '\n```\n'
  done
} > "$arch/c4.md"
