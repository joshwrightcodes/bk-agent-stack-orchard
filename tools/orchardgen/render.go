package main

import (
	"bytes"
	"fmt"
	"go/format"
	"sort"
	"strings"
)

// primitives that a field may use directly.
var primitives = map[string]bool{
	"string": true, "bool": true, "int": true, "int64": true, "uint64": true,
	"float64": true, "time.Time": true, "[]string": true,
}

// render writes the Go file for a version of the upstream types.
func render(version string, types map[string]*declaration) ([]byte, error) {
	body, err := renderTypes(types, version)
	if err != nil {
		return nil, err
	}

	var b bytes.Buffer

	fmt.Fprintf(&b, `// Code generated by %s. DO NOT EDIT.
//
// Source: github.com/%s at %s, packages pkg/resource/v1.
// Regenerate with: go generate ./internal/orchard/
//
// These structures carry the shape of the Orchard API that this controller uses. The controller
// imports no Orchard package, so this file is how the shape stays current: a pipeline runs the
// generator and fails when the result is different from the file in the tree.
//
// A field whose type this project does not read carries json.RawMessage, because the shape
// matters and the content does not.

package orchard

%s
// OrchardVersion is the version whose types this file follows.
const OrchardVersion = %q

`, generatedBy, upstreamRepo, version, imports(body), version)

	b.WriteString(body)

	source, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting the generated file: %w\n%s", err, b.String())
	}

	return source, nil
}

// renderTypes writes the structures, which decides what the file imports.
func renderTypes(types map[string]*declaration, version string) (string, error) {
	var b strings.Builder

	for _, want := range wanted {
		declaration, ok := types[want.upstream]
		if !ok {
			return "", fmt.Errorf("orchard %s has no type %s", version, want.upstream)
		}

		fmt.Fprintf(&b, "// %s\n//\n// Orchard calls it %s.\ntype %s struct {\n",
			want.comment, want.upstream, want.local)

		for _, f := range flatten(declaration, types, map[string]bool{}) {
			if f.comment != "" {
				fmt.Fprintf(&b, "\t// %s\n", f.comment)
			}
			fmt.Fprintf(&b, "\t%s %s `json:%q`\n", f.name, resolve(f.goType, types), f.tag)
		}

		b.WriteString("}\n\n")
	}

	return b.String(), nil
}

// imports gives the import block that the generated structures need, and nothing more. An import
// that no field uses would not compile.
func imports(body string) string {
	var needed []string

	if strings.Contains(body, "json.RawMessage") {
		needed = append(needed, `"encoding/json"`)
	}
	if strings.Contains(body, "time.Time") {
		needed = append(needed, `"time"`)
	}

	if len(needed) == 0 {
		return ""
	}

	return "import (\n\t" + strings.Join(needed, "\n\t") + "\n)\n"
}

// flatten gives the fields of a structure and of everything that it embeds, because an embedded
// structure carries its fields on the wire.
func flatten(d *declaration, types map[string]*declaration, seen map[string]bool) []field {
	fields := append([]field{}, d.fields...)

	for _, name := range d.embedded {
		if seen[name] {
			continue
		}
		seen[name] = true

		embedded, ok := types[name]
		if !ok {
			continue
		}

		fields = append(fields, flatten(embedded, types, seen)...)
	}

	sort.SliceStable(fields, func(i, j int) bool { return fields[i].wire < fields[j].wire })

	return fields
}

// resolve turns an upstream type into one that this project can carry. A named type that stands
// for a map, a slice, or a primitive becomes that. Anything else becomes json.RawMessage,
// because this controller does not read it.
func resolve(goType string, types map[string]*declaration) string {
	pointer := strings.HasPrefix(goType, "*")
	goType = strings.TrimPrefix(goType, "*")

	// A type that this file also generates keeps its shape, under the name of this project.
	for _, want := range wanted {
		if want.upstream == goType {
			if pointer {
				return "*" + want.local
			}

			return want.local
		}
	}

	if primitives[goType] {
		return goType
	}

	if strings.HasPrefix(goType, "[]") {
		element := resolve(strings.TrimPrefix(goType, "[]"), types)
		if element == "json.RawMessage" {
			return "json.RawMessage"
		}

		return "[]" + element
	}

	if strings.HasPrefix(goType, "map[") {
		return goType
	}

	declaration, ok := types[goType]
	if !ok || declaration.alias == nil {
		return "json.RawMessage"
	}

	underlying := expression(declaration.alias)
	if underlying == goType {
		return "json.RawMessage"
	}

	return resolve(underlying, types)
}
